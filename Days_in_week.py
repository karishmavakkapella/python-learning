#Day of week
n = int(input("Enter a number(1-7):"))
if n>=1 and n<=7:
  if n==1:
      print("Sunday")
  elif n==2:
      print("Monday")
  elif n==3:
      print("Tuesday")
  elif n==4:
      print("Wednesday")
  elif n==5:
      print("Thursday")
  elif n==6:
      print("Friday")
  else:
      print("Saturday")
